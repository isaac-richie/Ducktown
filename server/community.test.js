  const start=async()=>{const app=await createApp({dataFile});app.server.listen(0,'127.0.0.1');await new Promise(resolve=>app.server.once('listening',resolve));return {app,base:`http://127.0.0.1:${app.server.address().port}`};};
  let {app,base}=await start();
