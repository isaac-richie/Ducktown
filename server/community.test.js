  assert.equal((await request('/api/v1/profiles/flock_alice/follow','PUT',undefined,alice.cookie)).status,400);
  assert.equal((await request('/api/v1/profiles/flock_alice/follow','PUT',undefined,bob.cookie)).status,200);
  assert.equal((await request('/api/v1/profiles/flock_alice/follow','PUT',undefined,bob.cookie)).status,200);
  assert.equal((await (await request('/api/v1/profiles/flock_alice')).json()).profile.followers,1);
  assert.equal((await request('/api/v1/saves/idea/not-real','PUT',undefined,bob.cookie)).status,404);
