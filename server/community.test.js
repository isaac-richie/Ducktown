test('two store connections serialize writes without losing either account',async t=>{
  const folder=await mkdtemp(path.join(os.tmpdir(),'ducktown-db-concurrent-'));
  t.after(()=>rm(folder,{recursive:true,force:true}));
  const dataFile=path.join(folder,'town.json'),one=new Store(dataFile),two=new Store(dataFile);
  await one.open();await two.open();
  t.after(()=>{one.close();two.close();});
  await Promise.all([one.createUser('first_duck','test-hash'),two.createUser('other_duck','test-hash')]);
  one.refresh();two.refresh();
  assert.equal(one.state.users.length,2);
  assert.equal(two.state.users.length,2);
  assert.equal(readStoredState(dataFile).users.length,2);
});

