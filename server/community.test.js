  assert.equal((await request('/api/v1/saves/challenge/greeting','PUT',undefined,bob.cookie)).status,200);
  const post=(await (await request('/api/v1/posts','POST',{text:'A real build note'},alice.cookie)).json()).post;
  assert.equal((await request(`/api/v1/saves/post/${post.id}`,'PUT',undefined,bob.cookie)).status,200);
  assert.equal((await request(`/api/v1/posts/${post.id}/replies`,'POST',{text:'Welcome!'},bob.cookie)).status,201);
  const aliceNotices=(await (await request('/api/v1/notifications','GET',undefined,alice.cookie)).json()).notifications;
  assert.deepEqual(aliceNotices.map(item=>item.kind),['reply','follow']);
  assert.equal((await (await request('/api/v1/notifications','GET',undefined,bob.cookie)).json()).notifications.length,0);
  assert.equal((await request('/api/v1/notifications/read','POST',{},bob.cookie)).status,200);
  assert.equal((await request('/api/v1/notifications/read','POST',{},alice.cookie)).status,200);
  assert.ok((await (await request('/api/v1/notifications','GET',undefined,alice.cookie)).json()).notifications.every(item=>item.read));
