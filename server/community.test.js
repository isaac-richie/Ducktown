  assert.equal((await request('/api/v1/profile','PUT',{name:'<script>',bio:'Hi',colorway:'cream',publicProfile:true,ownerId:bob.user.id},alice.cookie)).status,400);
  assert.equal((await request('/api/v1/profile','PUT',{name:'A'.repeat(41),bio:'Hi',colorway:'cream',publicProfile:true},alice.cookie)).status,400);
  const profile={name:'Amber',bio:'Curious about tiny dances <3',colorway:'lavender',publicProfile:true};
